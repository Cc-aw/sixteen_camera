#!/usr/bin/env python3
"""Exact integer tables for the existing Q24 distance and Q31 score ABI."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
lines = ['`timescale 1ns/1ps', '// Generated by scripts/generate_yolov5nu_bbox_lut.py; integer arithmetic only.',
'module yolov5nu_bbox_lut(',
'    input wire [1:0] head,',
'    input wire [31:0] distances,',
'    input wire [7:0] score,',
'    output wire [191:0] offsets,',
'    output reg [15:0] score_q15', ');',
'    function automatic [47:0] offset(input [9:0] key);', '        case(key)']
for head, stride in enumerate((8,16,32)):
    for raw in range(256):
        signed = raw if raw < 128 else raw-256
        value = signed*stride*1894981
        lines.append(f"        10'd{head*256+raw}: offset=48'h{value & ((1<<48)-1):012x};")
lines += ["        default: offset=0;", '        endcase', '    endfunction',
'    for(genvar i=0;i<4;i=i+1) begin : g_offset',
'        assign offsets[i*48+:48]=offset({head,distances[i*8+:8]});',
'    end', '    always @* case(score)']
for raw in range(256):
    value=((raw*16171270+32768)>>16)&0xffff
    lines.append(f"        8'd{raw}: score_q15=16'd{value};")
lines += ['    endcase', 'endmodule', '']
(ROOT/'rtl/ai/postprocess/yolov5nu_bbox_lut.sv').write_text('\n'.join(lines))
