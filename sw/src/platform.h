#include <stdint.h>

#define SOC_CLOCK_HZ UINT64_C(100000000)
#define UART_BAUD    UINT64_C(115200)
#define UART_BASE    ((uintptr_t)0x10020000UL)

#define AXI_GPIO_BASE ((uintptr_t)0x40000000UL)
#define AXI_IIC_BASE  ((uintptr_t)0x40010000UL)
#define VPHY_BASE     ((uintptr_t)0x40020000UL)
#define HDMI_RX_BASE  ((uintptr_t)0x40030000UL)
#define HDMI_TX_BASE  ((uintptr_t)0x40040000UL)
#define HDMI_TX_VTC_BASE ((uintptr_t)0x40050000UL)
#define FRAMEBUFFER_BASE ((uintptr_t)0x40100000UL)

#define LOCAL_CAMERA_COUNT 8U
#define LOCAL_CAMERA_GLOBAL_BASE 1U
#define CAMERA_PRESENT_MASK UINT32_C(0xFF)

#define CAMERA_CH1_BLOCK_BASE ((uintptr_t)0x40110000UL)
#define CAMERA_CH2_BLOCK_BASE ((uintptr_t)0x40114000UL)
#define CAMERA_CH3_BLOCK_BASE ((uintptr_t)0x40118000UL)
#define CAMERA_CH4_BLOCK_BASE ((uintptr_t)0x4011C000UL)
#define CAMERA_CH5_BLOCK_BASE ((uintptr_t)0x40120000UL)
#define CAMERA_CH6_BLOCK_BASE ((uintptr_t)0x40124000UL)
#define CAMERA_CH7_BLOCK_BASE ((uintptr_t)0x40128000UL)
#define CAMERA_CH8_BLOCK_BASE ((uintptr_t)0x4012C000UL)
#define CAMERA_CSI_OFFSET      0x1000U

#define FRAMEBUFFER_CONTROL      0x00U
#define FRAMEBUFFER_STATUS       0x04U
#define FRAMEBUFFER_WIDTH        0x08U
#define FRAMEBUFFER_HEIGHT       0x0CU
#define FRAMEBUFFER_STRIDE       0x10U
#define FRAMEBUFFER_COUNT        0x14U
#define FRAMEBUFFER_DISPLAY_CH   0x18U
#define FRAMEBUFFER_PRESENT_MASK 0x1CU
#define FRAMEBUFFER_BASE0        0x20U
#define FRAMEBUFFER_BUFFER_STRIDE 0x40U
#define FRAMEBUFFER_DISPLAY_MODE  0x44U
#define FRAMEBUFFER_WRITER_COUNT(channel) (0x80U + ((channel) * 4U))
#define FRAMEBUFFER_DROP_COUNT(channel) (0xA0U + ((channel) * 4U))
#define FRAMEBUFFER_MALFORMED(channel) (0xC0U + ((channel) * 4U))
#define FRAMEBUFFER_READER_COUNT 0xE0U
#define FRAMEBUFFER_UNDERFLOW    0xE4U
#define FRAMEBUFFER_READER_BASE  0xE8U
#define FRAMEBUFFER_READER_DEBUG 0xECU
