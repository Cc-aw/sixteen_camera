#define FRAMEBUFFER_WRITER_PERF_MAX 0xF4U
#define FRAMEBUFFER_WRITER_PERF_AW_STALL 0xF8U
#define FRAMEBUFFER_WRITER_PERF_W_STALL 0xFCU
#define FRAMEBUFFER_WRITER_PERF_B_STALL 0x100U
#define FRAMEBUFFER_WRITER_PERF_ISSUED 0x104U
#define FRAMEBUFFER_WRITER_PERF_COMPLETED 0x108U
#define FRAMEBUFFER_WRITER_PERF_ERRORS 0x10CU

#define GPIO_OUT_TX_ENABLE   (UINT32_C(1) << 0)
#define GPIO_OUT_CLK_RESET_N (UINT32_C(1) << 1)
#define GPIO_IN_RX_PWR_DET (UINT32_C(1) << 0)
#define GPIO_IN_TX_HPD     (UINT32_C(1) << 1)
#define GPIO_IN_CLK_LOL    (UINT32_C(1) << 2)
#define GPIO_IN_CLK_INT    (UINT32_C(1) << 3)
#define GPIO_IN_TX_LOCKED  (UINT32_C(1) << 4)

#define HDMI_CLK_I2C_ADDRESS UINT32_C(0x7C)

#endif
