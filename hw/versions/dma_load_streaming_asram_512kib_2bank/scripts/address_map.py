#!/usr/bin/env python3
"""Generate ASRAM constants and audit the explicitly selected baseline memory map."""
import argparse
import hashlib
import json
from pathlib import Path

FEATURE = Path(__file__).resolve().parents[1]


def load_map():
    m = json.loads((FEATURE / 'manifests/activation_sram.json').read_text())
    assert len(m['base_by_frontend_lane']) == 3
    assert m['physical_bytes_per_bank'] == 0x240000
    assert m['logical_arena_bytes'] == 2217600
    assert m['data_width_bits'] == 256 and m['max_transfer_bytes'] == 64
    assert m['reserved_stride_bytes'] == 0x400000 and m['control_bytes'] == 4096
    assert m['read_pipeline_cycles'] == 2
    assert m['request_queue_beats'] == 64 and m['response_queue_beats'] == 8
    assert m['target_slr_by_frontend_lane'] == [0, 1, 3]
    assert m['native_opcode_by_frontend_lane'] == [11, 43, 91]
    assert m['build_rocc_index_by_frontend_lane'] == [0, 1, 2]
    ranges = [(b, b + m['reserved_stride_bytes']) for b in m['base_by_frontend_lane']]
    ranges.append((m['control_base'], m['control_base'] + m['control_bytes']))
    for i, (start, end) in enumerate(ranges):
        assert 0 <= start < end <= 1 << 32
        assert start % (m['reserved_stride_bytes'] if i < 3 else m['control_bytes']) == 0
        assert all(end <= a or start >= b for a, b in ranges[:i])
    return m, ranges


def generated_files(m):
    bases = ', '.join(f'BigInt("{b:x}", 16)' for b in m['base_by_frontend_lane'])
    scala = f'''// Generated by scripts/address_map.py; edit manifests/activation_sram.json.
package freechips.rocketchip.tile.commandfrontend
import chisel3._
import freechips.rocketchip.diplomacy.AddressSet
import org.chipsalliance.cde.config.Field
case object ActivationSramKey extends Field[Boolean](false)
object ActivationSramMap {{
  val bases = Seq({bases})
  val bytes = {m['physical_bytes_per_bank']}
  val arenaBytes = {m['logical_arena_bytes']}
  val stride = {m['reserved_stride_bytes']}
  val controlBase = BigInt("{m['control_base']:x}", 16)
  val controlBytes = {m['control_bytes']}
  val clockHz = {m['clock_hz']}
  val reserved = bases.map(b => AddressSet(b, stride - 1)) :+
    AddressSet(controlBase, controlBytes - 1)
  def containsRange(start: UInt, endExclusive: UInt): Bool =
    bases.map(b => start >= b.U && endExclusive > start && endExclusive <= (b + bytes).U).reduce(_ || _)
}}
'''
    dma = '''// Generated from the same ASRAM manifest as the TL managers.
package gemmini
import chisel3._
object ActivationSramDmaAddress {
  def localRange(start: UInt, endExclusive: UInt): Bool =
    freechips.rocketchip.tile.commandfrontend.ActivationSramMap.containsRange(start, endExclusive)
}
'''
    c = '''/* Generated by scripts/address_map.py. */
#ifndef ACTIVATION_SRAM_MAP_H
#define ACTIVATION_SRAM_MAP_H
#include <stdint.h>
'''
    for key, value in [('ABI_MAJOR', m['abi_major']), ('ABI_MINOR', m['abi_minor']),
                       ('BANK_COUNT', 3), ('BYTES_PER_BANK', m['physical_bytes_per_bank']),
                       ('ARENA_BYTES', m['logical_arena_bytes']),
                       ('RESERVED_STRIDE', m['reserved_stride_bytes']),
                       ('CONTROL_BASE', m['control_base']), ('CLOCK_HZ', m['clock_hz'])]:
        c += f'#define ASRAM_{key} UINT32_C(0x{value:x})\n'
    for lane, base in enumerate(m['base_by_frontend_lane']):
        c += f'#define ASRAM_BASE_{lane} UINT32_C(0x{base:x})\n'
    c += '#endif\n'
    return {
        'activation_sram/scala/ActivationSramMap.scala': scala,
        'soc_shell/npu100_video/src/main/scala/gemmini/ActivationSramDmaAddress.scala': dma,
        'software/include/activation_sram_map.h': c,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--baseline-memmap', type=Path)
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    m, ranges = load_map()
    for relative, content in generated_files(m).items():
        path = FEATURE / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit('Stale generated ASRAM constants: ' + relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.baseline_memmap:
        mapping = json.loads(args.baseline_memmap.read_text())['mapping']
        overlaps = []
        for entry in mapping:
            for b, size in zip(entry['base'], entry['size']):
                for a, e in ranges:
                    if a < b + size and b < e:
                        overlaps.append(dict(start=a, end=e, manager=entry))
        if overlaps:
            raise SystemExit('ASRAM overlaps baseline managers: ' + json.dumps(overlaps))
        report = dict(status='BASELINE_ADDRESS_MAP_PASS', final_negotiation='NOT_RUN',
                      baseline=str(args.baseline_memmap),
                      baseline_sha256=hashlib.sha256(args.baseline_memmap.read_bytes()).hexdigest(),
                      reserved_ranges=ranges, aliases_created=[], overlapping_managers=overlaps,
                      scope='Baseline published managers only; new DMA/CPU/RVV negotiation and alias behavior still require integration')
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(json.dumps(report, indent=2) + '\n')
    print('ASRAM_MAP_CONSTANTS=PASS baseline_checked=' + str(bool(args.baseline_memmap)))


if __name__ == '__main__':
    main()
