#!/usr/bin/env python3
"""Audit generated three-bank hierarchy and the actual negotiated PMA evidence."""
import argparse
import hashlib
import json
from pathlib import Path
import re

FEATURE = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rtl', type=Path, required=True)
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    rtl = args.rtl.resolve()
    tile = (rtl / 'RocketTile.sv').read_text()
    instances = re.findall(r'^  (ActivationSramTL(?:_\d+)?)\s+(\w+)\s*\(', tile, re.M)
    assert len(instances) == 3, ('Expected three real banks', instances)
    for module, instance in instances:
        body = (rtl / (module + '.sv')).read_text()
        assert len(re.findall(r'^  activation_sram_store\s+\w+\s*\(', body, re.M)) == 1, instance
    store = rtl / 'activation_sram_store.sv'
    emitted_lines = store.read_text().splitlines()
    # firtool adds its version banner and strips the final newline from
    # external resources. Require the remaining source to match exactly.
    if emitted_lines and re.fullmatch(r'// Generated by CIRCT firtool-\d+\.\d+\.\d+', emitted_lines[0]):
        emitted_lines = emitted_lines[1:]
    assert emitted_lines == (FEATURE / 'activation_sram/resources/activation_sram_store.sv').read_text().splitlines()
    assert '`define ASRAM_BEHAVIORAL' not in store.read_text(), 'Simulation model leaked into production'
    topology = next(rtl.parent.glob('*.activation_sram_topology.json'))
    pma = next(rtl.parent.glob('*.activation_sram_pma.json'))
    lanes = json.loads(topology.read_text())['lanes']
    assert [a['frontend_lane'] for a in lanes] == [0, 1, 2]
    assert [a['native_opcode'] for a in lanes] == [11, 43, 91]
    assert [a['build_rocc_index'] for a in lanes] == [0, 1, 2]
    assert [a['target_slr'] for a in lanes] == [0, 1, 3]
    visibility = json.loads(pma.read_text())
    assert visibility['status'] == 'PMA_NEGOTIATION_PASS'
    assert visibility['rvv_uses_dcache'] is True
    m = json.loads((FEATURE / 'manifests/activation_sram.json').read_text())
    for base in m['base_by_frontend_lane']:
        matches = [a for a in visibility['cpu_managers'] if any(
            (base & ~int(s['mask'], 16)) == int(s['base'], 16) for s in a['address_sets'])]
        assert len(matches) == 1
        manager = matches[0]
        assert manager['readable'] and manager['writable'] and manager['partial_write']
        assert not manager['cacheable'] and not manager['executable']
    inputs = [rtl / 'RocketTile.sv', store, topology, pma] + [rtl / (a + '.sv') for a, _ in instances]
    report = dict(status='GENERATED_STRUCTURE_AND_PMA_NEGOTIATION_PASS', banks=3,
                  physical_bytes_per_bank=m['physical_bytes_per_bank'], expected_uram=216,
                  physical_resources_synthesized=False, cpu_rvv_executed=False,
                  gemmini_numerical_integration=False,
                  sha256={str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs})
    if args.report:
        args.report.write_text(json.dumps(report, indent=2) + '\n')
    print('ASRAM_GENERATED_STRUCTURE=PASS banks=3 backing_copies_per_bank=1 pma=NEGOTIATED execution=NOT_RUN')


if __name__ == '__main__':
    main()
